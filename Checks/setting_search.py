"""Rebuild the native settings search rows from the actual SwiftUI scroll anchors."""
import argparse
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1] / "Sources/PiliNative"
output = root / "Settings/SettingSearchData.swift"

def collect():
    lines = []
    for file in sorted(root.rglob("*.swift")):
        if file == output:
            continue
        for slug in re.findall(r'\.settingAnchor\("([^"\\\n]+)"\)', file.read_text(encoding="utf-8")):
            where, sep, title = slug.partition("/")
            if not sep or not title.strip() or slug in lines:
                raise SystemExit(f"Invalid or duplicate search anchor: {file.name} {slug}")
            lines.append(slug)
    return sorted(lines)

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--write", action="store_true")
    opts = p.parse_args()
    rows = collect()
    # A single literal keeps Swift's device compiler from type-checking hundreds of initializers.
    code = "// Generated by Checks/setting_search.py --write\n" + \
        "enum SettingSearchData {\n  static let anchors = \"\"\"\n" + "\n".join(rows) + "\n\"\"\"\n}\n"
    if opts.write:
        output.write_text(code, encoding="utf-8", newline="\n")
    elif not output.exists() or output.read_text(encoding="utf-8") != code:
        raise SystemExit("Settings index is stale: run python3 Checks/setting_search.py --write")
    print(f"{len(rows)} settings search anchors matched their SwiftUI controls")
